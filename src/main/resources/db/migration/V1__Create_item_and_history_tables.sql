CREATE TABLE Item (
	Id BIGINT IDENTITY(1,1) PRIMARY KEY,
	Title NVARCHAR(400) NOT NULL,
	MediaType VARCHAR(20) NOT NULL,
	Stock INT NOT NULL CONSTRAINT CHECK_ITEM_STOCK CHECK (Stock >= 0),
	Price INT NOT NULL CONSTRAINT CHECK_ITEM_PRICE CHECK (Price >= 0),
	ImageUrl VARCHAR(2048) NOT NULL,
	LastChange DATETIMEOFFSET NOT NULL,
	LastChangedBy BIGINT NOT NULL CONSTRAINT CHECK_ITEM_LAST_CHANGED_BY CHECK (LastChangedBy > 0)
 );
 
 CREATE TABLE ItemHistory (
 	HistoryEntryId BIGINT IDENTITY(1,1) PRIMARY KEY,
	Id BIGINT NOT NULL CONSTRAINT ID_CHECK CHECK (Id > 0),
	Title NVARCHAR(400) NOT NULL,
	MediaType VARCHAR(20) NOT NULL,
	Stock INT NOT NULL CONSTRAINT CHECK_ITEM_HISTORY_STOCK CHECK (Stock >= 0),
	Price INT NOT NULL CONSTRAINT CHECK_ITEM_HISTORY_PRICE CHECK (Price >= 0),
	ImageUrl VARCHAR(2048) NOT NULL,
	LastChange DATETIMEOFFSET NOT NULL,
	LastChangedBy BIGINT NOT NULL CONSTRAINT CHECK_ITEM_HISTORY_LAST_CHANGED_BY CHECK (LastChangedBy > 0),
	Action VARCHAR(10) NOT NULL
 );